export interface IconProps {
  name: IconName
  size?: number
  strokeWidth?: number
  className?: string
  style?: CSSProperties
  /** 图标是装饰性时默认 aria-hidden；需要读屏时传入 label */
  label?: string
}

export function Icon({
  name,
  size = 16,
  strokeWidth = 1.5,
  className,
  style,
  label
}: IconProps): ReactElement {
  const a11y = label
    ? { role: 'img' as const, 'aria-label': label }
    : { 'aria-hidden': true as const, focusable: false as const }
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      {...a11y}
    >
      {PATHS[name]}
    </svg>
  )
}
